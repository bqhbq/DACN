import json
import random
from pathlib import Path
from typing import Any

from ..vehicles import VehicleFleet, VehicleType

INTERVAL = 10
START_TIME = 0
END_TIME = -1
VEHICLES = [
  (0.8, VehicleFleet.CAR),
  (0.2, VehicleFleet.TRUCK),
]
SEED = None

class FlowGenerator:
  def __init__(
    self,
    roadnet_json_file: str | Path,
    flow_json_file: str | Path
  ):
    self.roadnet_json_file = Path(roadnet_json_file).resolve()
    self.flow_json_file = Path(flow_json_file).resolve()
    
    self.roadnet: dict[str, Any] = {}
    self.intersections: dict[str, dict] = {}
    self.roads: dict[str, dict] = {}
    
    self.virtual_nodes: set[str] = set()
    self.virtual_node_edges: dict[str, dict] = {}

    self.flows: list[dict] = []
    
    self._load_roadnet()
    self._find_virtual_nodes()
    self._find_virtual_node_edges()

  def _load_roadnet(self):
    if not self.roadnet_json_file.is_file():
      raise FileNotFoundError(self.roadnet_json_file)
    
    with self.roadnet_json_file.open("r", encoding="utf-8") as file:
      self.roadnet = json.load(file)

    self.intersections = {
      node["id"]: node
      for node in self.roadnet.get("intersections", [])
    }
    self.roads = {
      road["id"]: road
      for road in self.roadnet.get("roads", [])
    }
    
  def _find_virtual_nodes(self):
    self.virtual_nodes = {
      node_id
      for node_id, node in self.intersections.items()
      if node.get("virtual", False)
    }

    if len(self.virtual_nodes) < 2:
      raise ValueError("At least two virtual nodes are required.")

  def _find_virtual_node_edges(self):
    self.virtual_node_edges = {
      node_id: {
        "in" : [],
        "out": []
      }
      for node_id in self.virtual_nodes
    }
    
    for road_id, road in self.roads.items():
      start = road.get("startIntersection")
      end = road.get("endIntersection")
      
      if start in self.virtual_nodes:
        self.virtual_node_edges[start]["out"].append(road_id)
        
      if end in self.virtual_nodes:
        self.virtual_node_edges[end]["in"].append(road_id)

  def generate(
    self,
    interval: int = INTERVAL,
    startTime: int = START_TIME,
    endTime: int = END_TIME,
    vehicles: list[tuple[float, VehicleType]] = VEHICLES,
    seed: int = SEED
  ):
    # 1. Initialize the random seed & vehicle distribution
    if seed is not None:
      random.seed(seed)
    dist = [(weight, vehicle_type) for weight, vehicle_type in vehicles]
    weights = [item[0] for item in dist]
    vehicle_types = [item[1] for item in dist]
    
    # 2. Randomly select a vehicle type for the flow
    #    Only define start and end roads, the flow will be generated by CityFlow based on the road network
    self.flows = []
    for start_node in self.virtual_nodes:
      for end_node in self.virtual_nodes:
        if start_node == end_node:
          continue
        
        start_roads = self.virtual_node_edges[start_node]["out"]
        end_roads = self.virtual_node_edges[end_node]["in"]
        
        for start_road in start_roads:
          for end_road in end_roads:
            selected_type: VehicleType = random.choices(vehicle_types, weights=weights, k=1)[0]
            flow = {
              "vehicle": selected_type.to_dict(),
              "route": [start_road, end_road],
              "interval": interval,
              "startTime": startTime,
              "endTime": endTime
            }
            self.flows.append(flow)
    
    # 3. Save the generated flows to a JSON file
    self.flow_json_file.parent.mkdir(parents=True, exist_ok=True)

    with self.flow_json_file.open("w", encoding="utf-8") as file:
      json.dump(self.flows, file, indent=2, ensure_ascii=False)